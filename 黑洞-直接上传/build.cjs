/* Build a single classic script so index.html works even from file://
   usage: node build.cjs
   - three.module.js: convert the final `export { ... }` into window.THREE
   - main.js: strip the ESM import, reuse window.THREE
   - writes app.js                                            */
const fs = require('fs');
const path = require('path');
const root = __dirname;

let three = fs.readFileSync(path.join(root, 'three.module.js'), 'utf8');
const i = three.lastIndexOf('export {');
const j = three.lastIndexOf('};');
if (i < 0 || j < i) throw new Error('export block not found');

const list = three.slice(i + 'export {'.length, j);
const pairs = list
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean)
  .map((s) => {
    const m = s.split(/\s+as\s+/);
    return m.length === 2 ? `${m[1]}: ${m[0]}` : `${m[0]}`;
  });

three = three.slice(0, i) + `\nwindow.THREE = { ${pairs.join(', ')} };\n`;

let main = fs.readFileSync(path.join(root, 'main.js'), 'utf8');
main = main.replace(/^import \* as THREE from [^;]+;\s*$/m, 'const THREE = window.THREE;\n');
if (main.includes('import * as THREE')) throw new Error('import not stripped');

const out = `/* generated by build.cjs — do not edit */
(function () {
"use strict";
${three}
})();
(function () {
"use strict";
${main}
})();
`;
fs.writeFileSync(path.join(root, 'app.js'), out);
console.log('app.js written:', (out.length / 1024).toFixed(0) + ' KB', '| exports:', pairs.length);
